# -*- coding: utf-8 -*-
"""把若干 .rc 片段拼成一个独立的 EClone.rc。

原因：VC6 的 RC.EXE 处理嵌套 #include 时，被包含文件里的 `IDD_xxx DIALOG` 会被
误判（报 RC2135 file not found: DIALOG）。拼成单文件即可绕开，且仍然只用一层标准头文件包含。

用法: python assemble_rc.py
"""
import os

# project root = the directory containing this tools/ dir (was hard-coded to D:\eclone)
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
PARTS = ["rc_head.rc", "resource.h", "bitmaps.rc", "menu_main.rc", "panes.rc", "ec_syscfg.rc"]
OUT = os.path.join(SRC, "EClone.rc")

buf = ["// ==== AUTO-GENERATED by tools/assemble_rc.py -- DO NOT EDIT ===="]
for p in PARTS:
    path = os.path.join(SRC, p)
    if not os.path.exists(path):
        continue
    buf.append("// ---------------- %s ----------------" % p)
    txt = open(path, encoding="utf-8-sig").read()   # utf-8-sig: 吃掉 BOM
    buf.append(txt.replace("\ufeff", "").rstrip("\n"))
    buf.append("")
open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(buf) + "\n")
print("assembled %s from %s" % (OUT, ", ".join(PARTS)))
